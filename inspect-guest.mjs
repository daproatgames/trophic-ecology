import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } }); page.setDefaultTimeout(5000);
await page.goto('http://127.0.0.1:5173/#/arcade/karting',{waitUntil:'domcontentloaded'}); await page.waitForTimeout(1000);
console.log('TEXT1',(await page.locator('body').innerText()).slice(0,300));
await page.getByRole('button',{name:'Explore first'}).click().catch(()=>{}); await page.waitForTimeout(500);
console.log('BUTTONS', await page.getByRole('button').allTextContents());
console.log('TEXT2',(await page.locator('body').innerText()).slice(0,700));
await page.screenshot({path:'/tmp/guest-inspect.png'});
await browser.close();
